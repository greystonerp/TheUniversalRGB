// Release signing tool for Universal RGB Control.
//
//   keygen <privateKeyFile> <publicKeySourceFile>   Create the release key pair (refuses to overwrite).
//   sign   <file> <privateKeyFile>                  Write <file>.sig (base64 ECDSA P-256 / SHA-256 signature).
//   verify <file> <publicKeySourceFile>             Check <file>.sig against the public key in the source file.
//
// The private key must stay on the maintainer's machine (never commit or upload it). Installed copies of the app
// only accept updates signed with it.

using System.Text.RegularExpressions;
using UniversalRGB.Core.Updates;

if (args.Length < 1)
{
    return Usage();
}

try
{
    switch (args[0])
    {
        case "keygen" when args.Length == 3:
        {
            var (privatePath, publicSource) = (args[1], args[2]);
            if (File.Exists(privatePath))
            {
                Console.Error.WriteLine($"A private key already exists at {privatePath}. Refusing to overwrite it.");
                return 2;
            }

            var (privateKey, publicKey) = ReleaseSignature.CreateKeyPair();
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(privatePath))!);
            File.WriteAllText(privatePath, privateKey);
            File.WriteAllText(publicSource, $$"""
                // Generated by tools/UniversalRGB.ReleaseTool (keygen). This is the PUBLIC half of the release signing key.
                // Installed copies only accept updates whose signature verifies against this key.
                namespace UniversalRGB.Desktop.Services;

                internal static class ReleaseKey
                {
                    public const string PublicKey = "{{publicKey}}";
                }

                """);
            Console.WriteLine($"Private key: {Path.GetFullPath(privatePath)}  (keep it safe and back it up; never commit it)");
            Console.WriteLine($"Public key written to {publicSource}");
            return 0;
        }

        case "sign" when args.Length == 3:
        {
            var (file, privatePath) = (args[1], args[2]);
            var signature = ReleaseSignature.Sign(file, File.ReadAllText(privatePath));
            var publicKey = ReleaseSignature.PublicKeyFromPrivate(File.ReadAllText(privatePath));
            if (!ReleaseSignature.Verify(file, signature, publicKey))
            {
                Console.Error.WriteLine("Self-check failed: the new signature does not verify.");
                return 3;
            }

            File.WriteAllText(file + ".sig", signature);
            Console.WriteLine($"Signed {Path.GetFileName(file)} -> {Path.GetFileName(file)}.sig");
            return 0;
        }

        case "verify" when args.Length == 3:
        {
            var (file, publicSource) = (args[1], args[2]);
            var match = Regex.Match(File.ReadAllText(publicSource), "PublicKey\\s*=\\s*\"([^\"]+)\"");
            if (!match.Success)
            {
                Console.Error.WriteLine("No public key found in " + publicSource);
                return 2;
            }

            var ok = ReleaseSignature.Verify(file, File.ReadAllText(file + ".sig"), match.Groups[1].Value);
            Console.WriteLine(ok ? "Signature OK" : "SIGNATURE INVALID");
            return ok ? 0 : 1;
        }

        default:
            return Usage();
    }
}
catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or System.Security.Cryptography.CryptographicException or ArgumentException)
{
    Console.Error.WriteLine(ex.Message);
    return 1;
}

static int Usage()
{
    Console.Error.WriteLine("usage: keygen <privateKeyFile> <publicKeySourceFile> | sign <file> <privateKeyFile> | verify <file> <publicKeySourceFile>");
    return 64;
}
